using System.Text;

namespace BB84.SourceGenerators.Helpers;

/// <summary>
/// A lightweight wrapper around <see cref="StringBuilder"/> that provides automatic
/// indentation tracking and common code generation patterns for source generators.
/// </summary>
internal sealed class SourceBuilder
{
	private const int IndentSize = 2;
	private const int MaxIndentLevels = 20;
	private static readonly string[] Indents =
		[.. Enumerable.Range(0, MaxIndentLevels).Select(i => new string(' ', i * IndentSize))];
	private readonly StringBuilder _sb = new();

	/// <summary>
	/// Gets the current indentation level.
	/// </summary>
	public int IndentLevel { get; private set; }

	/// <summary>
	/// Appends an auto-generated warning comment block.
	/// </summary>
	/// <param name="toolName">The name of the tool that generated the code.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendAutoGeneratedWarning(string toolName)
	{
		_ = _sb.AppendLine("//------------------------------------------------------------------------------")
			.AppendLine("// <auto-generated>")
			.AppendLine("//     This code was generated by a tool.")
			.AppendLine($"//     Tool: {toolName}")
			.AppendLine("//")
			.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if")
			.AppendLine("//     the code is regenerated.")
			.AppendLine("// </auto-generated>")
			.AppendLine("//------------------------------------------------------------------------------");

		return this;
	}

	/// <summary>
	/// Appends the <c>#nullable enable</c> directive.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendNullableEnable()
	{
		_ = _sb.AppendLine("#nullable enable");
		return this;
	}

	/// <summary>
	/// Appends a using directive.
	/// </summary>
	/// <param name="namespace">The namespace to import.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendUsing(string @namespace)
	{
		_ = _sb.AppendLine($"using {@namespace};");
		return this;
	}

	/// <summary>
	/// Opens a namespace block with the given name.
	/// </summary>
	/// <param name="namespaceName">The namespace name.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenNamespace(string namespaceName)
	{
		_ = AppendLine($"namespace {namespaceName}");
		_ = OpenBrace();
		return this;
	}

	/// <summary>
	/// Closes the current namespace block.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseNamespace()
	{
		_ = CloseBrace();
		return this;
	}

	/// <summary>
	/// Opens outer (nesting) class declarations for the given list of outer classes.
	/// </summary>
	/// <param name="outerClasses">The list of outer classes from outermost to innermost.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenOuterClasses(IReadOnlyList<(string Accessibility, string Name)> outerClasses)
	{
		foreach ((string accessibility, string name) in outerClasses)
		{
			_ = AppendLine($"{accessibility} partial class {name}");
			_ = OpenBrace();
		}

		return this;
	}

	/// <summary>
	/// Opens outer (nesting) class declarations for the given list of outer classes, emitting the
	/// <c>static</c> modifier for static outer classes.
	/// </summary>
	/// <param name="outerClasses">The list of outer classes from outermost to innermost.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenOuterClasses(IReadOnlyList<(string Accessibility, string Name, bool IsStatic)> outerClasses)
	{
		foreach ((string accessibility, string name, bool isStatic) in outerClasses)
		{
			string staticKeyword = isStatic ? "static " : string.Empty;
			_ = AppendLine($"{accessibility} {staticKeyword}partial class {name}");
			_ = OpenBrace();
		}

		return this;
	}

	/// <summary>
	/// Closes outer (nesting) class declarations.
	/// </summary>
	/// <param name="outerClasses">The list of outer classes (used only for count).</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseOuterClasses(IReadOnlyList<(string Accessibility, string Name)> outerClasses)
		=> CloseBraces(outerClasses.Count);

	/// <inheritdoc cref="CloseOuterClasses(IReadOnlyList{ValueTuple{string, string}})"/>
	public SourceBuilder CloseOuterClasses(IReadOnlyList<(string Accessibility, string Name, bool IsStatic)> outerClasses)
		=> CloseBraces(outerClasses.Count);

	/// <summary>
	/// Appends the common header of a generated type file: the auto-generated warning, the
	/// <c>#nullable enable</c> directive, the using directives, an empty line, the namespace
	/// block and the outer (nesting) class declarations.
	/// </summary>
	/// <param name="toolName">The name of the tool that generated the code.</param>
	/// <param name="namespaceName">The namespace name.</param>
	/// <param name="outerClasses">The list of outer classes from outermost to innermost.</param>
	/// <param name="usings">The namespaces to import, in emission order.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder BeginTypeFile(string toolName, string namespaceName, IReadOnlyList<(string Accessibility, string Name)> outerClasses, IReadOnlyList<string> usings)
	{
		_ = AppendAutoGeneratedWarning(toolName);
		_ = AppendNullableEnable();

		foreach (string @namespace in usings)
			_ = AppendUsing(@namespace);

		_ = AppendLine();
		_ = OpenNamespace(namespaceName);
		_ = OpenOuterClasses(outerClasses);
		return this;
	}

	/// <summary>
	/// Appends the common footer of a generated type file opened via <see cref="BeginTypeFile"/>:
	/// closes the outer (nesting) class declarations and the namespace block.
	/// </summary>
	/// <param name="outerClasses">The list of outer classes (used only for count).</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder EndTypeFile(IReadOnlyList<(string Accessibility, string Name)> outerClasses)
	{
		_ = CloseOuterClasses(outerClasses);
		_ = CloseNamespace();
		return this;
	}

	/// <summary>
	/// Opens a class declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="className">The class name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenClass(string accessibility, string className, string? baseTypes = null)
		=> OpenType($"{accessibility} partial class {className}", baseTypes);

	/// <summary>
	/// Opens a sealed class declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="className">The class name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenSealedClass(string accessibility, string className, string? baseTypes = null)
		=> OpenType($"{accessibility} sealed class {className}", baseTypes);

	/// <summary>
	/// Closes the current class block.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseClass()
	{
		_ = CloseBrace();
		return this;
	}

	/// <summary>
	/// Opens a struct declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="structName">The struct name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenStruct(string accessibility, string structName, string? baseTypes = null)
		=> OpenType($"{accessibility} partial struct {structName}", baseTypes);

	/// <summary>
	/// Closes the current struct block.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseStruct()
	{
		_ = CloseBrace();
		return this;
	}

	/// <summary>
	/// Opens a record declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="recordName">The record name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenRecord(string accessibility, string recordName, string? baseTypes = null)
		=> OpenType($"{accessibility} partial record {recordName}", baseTypes);

	/// <summary>
	/// Opens a sealed record declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="recordName">The record name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenSealedRecord(string accessibility, string recordName, string? baseTypes = null)
		=> OpenType($"{accessibility} sealed partial record {recordName}", baseTypes);

	/// <summary>
	/// Closes the current record block.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseRecord()
	{
		_ = CloseBrace();
		return this;
	}

	/// <summary>
	/// Opens a class or record declaration, for generators that support both class and record targets.
	/// </summary>
	/// <param name="isRecord">When <see langword="true"/>, opens a record declaration; otherwise, a class declaration.</param>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="typeName">The class or record name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenClassOrRecord(bool isRecord, string accessibility, string typeName, string? baseTypes = null)
		=> isRecord ? OpenRecord(accessibility, typeName, baseTypes) : OpenClass(accessibility, typeName, baseTypes);

	/// <summary>
	/// Closes the current class or record block opened via <see cref="OpenClassOrRecord"/>.
	/// </summary>
	/// <param name="isRecord">When <see langword="true"/>, closes a record declaration; otherwise, a class declaration.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseClassOrRecord(bool isRecord)
		=> isRecord ? CloseRecord() : CloseClass();

	/// <summary>
	/// Opens a record struct declaration.
	/// </summary>
	/// <param name="accessibility">The accessibility modifier.</param>
	/// <param name="recordStructName">The record struct name.</param>
	/// <param name="baseTypes">Optional base types / interfaces to implement.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenRecordStruct(string accessibility, string recordStructName, string? baseTypes = null)
		=> OpenType($"{accessibility} partial record struct {recordStructName}", baseTypes);

	/// <summary>
	/// Closes the current record struct block.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseRecordStruct()
	{
		_ = CloseBrace();
		return this;
	}

	/// <summary>
	/// Appends a line with the current indentation followed by the specified text.
	/// </summary>
	/// <param name="text">The text to append.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendLine(string text)
	{
		AppendIndent();
		_ = _sb.AppendLine(text);
		return this;
	}

	/// <summary>
	/// Appends a single-line XML documentation summary block.
	/// </summary>
	/// <param name="text">The summary text, without the leading <c>///</c>.</param>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendSummary(string text)
	{
		_ = AppendLine("/// <summary>");
		_ = AppendLine($"/// {text}");
		_ = AppendLine("/// </summary>");
		return this;
	}

	/// <summary>
	/// Appends an empty line.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder AppendLine()
	{
		_ = _sb.AppendLine();
		return this;
	}

	/// <summary>
	/// Opens a brace block (appends '{' and increases indentation).
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder OpenBrace()
	{
		AppendIndent();
		_ = _sb.AppendLine("{");
		IndentLevel++;
		return this;
	}

	/// <summary>
	/// Closes a brace block (decreases indentation and appends '}').
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder CloseBrace()
	{
		IndentLevel--;
		AppendIndent();
		_ = _sb.AppendLine("}");
		return this;
	}

	/// <summary>
	/// Increases the indentation level by one.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder Indent()
	{
		IndentLevel++;
		return this;
	}

	/// <summary>
	/// Decreases the indentation level by one.
	/// </summary>
	/// <returns>The current <see cref="SourceBuilder"/> instance.</returns>
	public SourceBuilder Outdent()
	{
		if (IndentLevel > 0)
			IndentLevel--;
		return this;
	}

	/// <inheritdoc/>
	public override string ToString()
		=> _sb.ToString();

	private SourceBuilder OpenType(string header, string? baseTypes)
	{
		_ = AppendLine(baseTypes is not null ? $"{header} : {baseTypes}" : header);
		_ = OpenBrace();
		return this;
	}

	private SourceBuilder CloseBraces(int count)
	{
		for (int i = 0; i < count; i++)
			_ = CloseBrace();

		return this;
	}

	private void AppendIndent()
		=> _sb.Append(IndentLevel < MaxIndentLevels ? Indents[IndentLevel] : new string(' ', IndentLevel * IndentSize));
}
