using System.Collections.Immutable;

using BB84.SourceGenerators.Attributes;
using BB84.SourceGenerators.Extensions;
using BB84.SourceGenerators.Helpers;
using BB84.SourceGenerators.Models;
using BB84.SourceGenerators.Requests;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace BB84.SourceGenerators;

/// <summary>
/// Responsible for generating enumerator extensions for enumerators marked
/// with the <see cref="GenerateEnumeratorExtensionsAttribute"/> attribute.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class EnumeratorExtensionsGenerator : IIncrementalGenerator
{
	private static readonly (string MetadataName, string TypeName, string ShortName) AttributeNames =
		GeneratorHelpers.GetAttributeNames<GenerateEnumeratorExtensionsAttribute>();

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
		=> GeneratorHelpers.RegisterRequestGenerator<EnumeratorExtensionsRequest>(context, AttributeNames.MetadataName, Predicate, Transform, TrackingNames.EnumeratorExtensions, Execute);

	private static void Execute(SourceProductionContext context, EnumeratorExtensionsRequest request)
	{
		string enumName = request.EnumName;
		EquatableArray<(string Name, string? Description, bool IsAlias)> members = request.Members;

		SourceBuilder sb = new();

		sb.AppendAutoGeneratedWarning(GeneratorNames.EnumeratorExtensionsGeneratorFullName);
		sb.AppendNullableEnable();
		sb.AppendUsing(NamespaceNames.System);
		sb.AppendUsing(NamespaceNames.SystemCollectionsGeneric);
		sb.AppendUsing(NamespaceNames.SystemComponentModel);
		sb.AppendLine();
		sb.OpenNamespace(request.NamespaceName);

		AppendClassStart(sb, enumName);

		AppendToStringFast(sb, enumName, members);

		if (request.IsFlags)
			AppendToStringFastFlags(sb, enumName, request.FlagMembers);

		AppendIsDefinedFast(sb, enumName, members);
		AppendTryParseFast(sb, enumName, members);

		if (request.IsFlags)
			AppendTryParseFastFlags(sb, enumName);

		AppendGetDescriptionFast(sb, enumName, members);
		AppendGetNamesFast(sb, enumName, members);
		AppendGetValuesFast(sb, enumName, members);

		sb.CloseClass();
		sb.CloseNamespace();

		context.AddSource(GeneratorHelpers.BuildHintName(enumName), sb.ToString());
	}

	private static GeneratorResult<EnumeratorExtensionsRequest>? Transform(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
	{
		if (context.TargetNode is not EnumDeclarationSyntax enumDeclaration)
			return null;

		ImmutableArray<EnumMemberDeclarationSyntax> members = [.. enumDeclaration.Members
				.OfType<EnumMemberDeclarationSyntax>()];

		if (!members.Any())
			return null;

		SemanticModel semanticModel = context.SemanticModel;
		INamedTypeSymbol? descriptionAttributeSymbol = semanticModel.Compilation.GetTypeByMetadataName(TypeNames.DescriptionAttribute);

		EquatableArray<(string Name, string? Description, bool IsAlias)> memberInfos = GetMemberInfos(members, semanticModel, descriptionAttributeSymbol, cancellationToken);

		bool isFlags = IsFlagsEnum(context.TargetSymbol, semanticModel);
		EquatableArray<string> flagMembers = isFlags
			? GetSingleBitMemberNames(members, semanticModel, cancellationToken)
			: EquatableArray<string>.Empty;

		return GeneratorResult<EnumeratorExtensionsRequest>.FromRequest(new EnumeratorExtensionsRequest(enumDeclaration.Identifier.Text, enumDeclaration.GetNamespace(), memberInfos, isFlags, flagMembers));
	}

	private static EquatableArray<(string Name, string? Description, bool IsAlias)> GetMemberInfos(ImmutableArray<EnumMemberDeclarationSyntax> members, SemanticModel semanticModel, INamedTypeSymbol? descriptionAttributeSymbol, CancellationToken cancellationToken)
	{
		List<(string Name, string? Description, bool IsAlias)> memberInfos = [];
		HashSet<ulong> seenValues = [];

		foreach (EnumMemberDeclarationSyntax member in members)
		{
			// A member whose value was already declared is an alias; the first declared member of a value wins.
			bool isAlias = semanticModel.GetDeclaredSymbol(member, cancellationToken) is IFieldSymbol { HasConstantValue: true } field
				&& !seenValues.Add(ToUInt64(field.ConstantValue));

			memberInfos.Add((member.Identifier.Text, GetDescriptionFromAttributes(member, semanticModel, descriptionAttributeSymbol), isAlias));
		}

		return memberInfos.ToEquatableArray();
	}

	private static EquatableArray<string> GetSingleBitMemberNames(ImmutableArray<EnumMemberDeclarationSyntax> members, SemanticModel semanticModel, CancellationToken cancellationToken)
	{
		List<string> names = [];
		HashSet<ulong> seenBits = [];

		foreach (EnumMemberDeclarationSyntax member in members)
		{
			if (semanticModel.GetDeclaredSymbol(member, cancellationToken) is not IFieldSymbol { HasConstantValue: true } field)
				continue;

			ulong bits = ToUInt64(field.ConstantValue);

			// Only distinct single-bit members; the first declared alias of a bit wins.
			if (bits != 0 && (bits & (bits - 1)) == 0 && seenBits.Add(bits))
				names.Add(member.Identifier.Text);
		}

		return names.ToEquatableArray();
	}

	// Signed values go through the unsigned type of the same width, so the sign bit stays a single bit.
	private static ulong ToUInt64(object? value)
		=> value switch
		{
			sbyte v => unchecked((byte)v),
			short v => unchecked((ushort)v),
			int v => unchecked((uint)v),
			long v => unchecked((ulong)v),
			byte v => v,
			ushort v => v,
			uint v => v,
			ulong v => v,
			_ => 0
		};

	private static bool IsFlagsEnum(ISymbol enumSymbol, SemanticModel semanticModel)
	{
		INamedTypeSymbol? flagsAttributeSymbol = semanticModel.Compilation.GetTypeByMetadataName(TypeNames.FlagsAttribute);

		return flagsAttributeSymbol is not null
			&& enumSymbol.GetAttributes().Any(attribute => SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, flagsAttributeSymbol));
	}

	private static bool Predicate(SyntaxNode node, CancellationToken cancellationToken)
		=> node is EnumDeclarationSyntax;

	private static void AppendClassStart(SourceBuilder sb, string enumName)
	{
		sb.AppendSummary($"The <see cref=\"{enumName}Extensions\"/> class provides extension methods for the <see cref=\"{enumName}\"/> enumeration.");
		sb.AppendLine($"public static partial class {enumName}Extensions");
		sb.OpenBrace();
	}

	private static void AppendToStringFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendSummary("Returns the name of the enumeration <paramref name=\"value\"/> as a string.");
		sb.AppendLine("/// <param name=\"value\">The enumeration value to convert to a string.</param>");
		sb.AppendLine("/// <returns>The name of the enumeration value as a string.</returns>");
		sb.AppendLine($"public static string ToStringFast(this {enumName} value)");
		sb.OpenBrace();
		sb.AppendLine("return value switch");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members.Where(member => !member.IsAlias))
		{
			sb.AppendLine($"{enumName}.{memberName} => nameof({enumName}.{memberName}),");
		}
		sb.AppendLine("_ => value.ToString()");
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendToStringFastFlags(SourceBuilder sb, string enumName, EquatableArray<string> flagMembers)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine("/// Returns the name of the enumeration <paramref name=\"value\"/> as a string. If the value is not");
		sb.AppendLine("/// a defined member, the names of all set single-bit members are joined with the");
		sb.AppendLine("/// <paramref name=\"separator\"/>, in declaration order.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"value\">The enumeration value to convert to a string.</param>");
		sb.AppendLine("/// <param name=\"separator\">The delimiter between the member names, for example <c>\"|\"</c>, <c>\",\"</c>, <c>\";\"</c> or <c>\" \"</c>.</param>");
		sb.AppendLine("/// <returns>");
		sb.AppendLine("/// The member name, the delimited names of the set single-bit members, or the result of");
		sb.AppendLine("/// <see cref=\"Enum.ToString()\"/> if the value contains bits not covered by a single-bit member.");
		sb.AppendLine("/// </returns>");
		sb.AppendLine($"public static string ToStringFast(this {enumName} value, string separator)");
		sb.OpenBrace();
		sb.AppendLine("if (value.IsDefinedFast())");
		sb.Indent();
		sb.AppendLine("return value.ToStringFast();");
		sb.Outdent();
		sb.AppendLine();
		sb.AppendLine($"{enumName} remaining = value;");
		sb.AppendLine("List<string> names = new List<string>();");
		foreach (string memberName in flagMembers)
		{
			sb.AppendLine($"if ((value & {enumName}.{memberName}) == {enumName}.{memberName})");
			sb.OpenBrace();
			sb.AppendLine($"names.Add(nameof({enumName}.{memberName}));");
			sb.AppendLine($"remaining &= ~{enumName}.{memberName};");
			sb.CloseBrace();
		}
		sb.AppendLine();
		sb.AppendLine("return remaining != 0 || names.Count == 0");
		sb.Indent();
		sb.AppendLine("? value.ToString()");
		sb.AppendLine(": string.Join(separator, names);");
		sb.Outdent();
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendIsDefinedFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine("/// Returns whether the specified enumeration <paramref name=\"value\"/> is defined");
		sb.AppendLine($"/// in the <see cref=\"{enumName}\"/>.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"value\">The enumeration value to check.</param>");
		sb.AppendLine("/// <returns>True if the enumeration value is defined; otherwise, false.</returns>");
		sb.AppendLine($"public static bool IsDefinedFast(this {enumName} value)");
		sb.OpenBrace();
		sb.AppendLine("return value switch");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members.Where(member => !member.IsAlias))
		{
			sb.AppendLine($"{enumName}.{memberName} => true,");
		}
		sb.AppendLine("_ => false");
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
		sb.AppendLine("/// <summary>");
		sb.AppendLine("/// Returns whether the specified enumeration <paramref name=\"name\"/> is defined");
		sb.AppendLine($"/// in the <see cref=\"{enumName}\"/>.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"name\">The name of the enumeration value to check.</param>");
		sb.AppendLine("/// <returns>True if the enumeration value is defined; otherwise, false.</returns>");
		sb.AppendLine($"public static bool IsDefinedFast(string name)");
		sb.OpenBrace();
		sb.AppendLine("return name switch");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members)
		{
			sb.AppendLine($"nameof({enumName}.{memberName}) => true,");
		}
		sb.AppendLine("_ => false");
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendTryParseFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine("/// Tries to convert the specified <paramref name=\"value\"/> to its");
		sb.AppendLine($"/// <see cref=\"{enumName}\"/> equivalent.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"value\">The name of the enumeration value to parse.</param>");
		sb.AppendLine("/// <param name=\"result\">The parsed enumeration value, or the default value if parsing failed.</param>");
		sb.AppendLine("/// <returns>True if <paramref name=\"value\"/> was parsed successfully; otherwise, false.</returns>");
		sb.AppendLine($"public static bool TryParseFast(string? value, out {enumName} result)");
		sb.OpenBrace();
		sb.AppendLine("switch (value)");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members)
		{
			sb.AppendLine($"case nameof({enumName}.{memberName}):");
			sb.Indent();
			sb.AppendLine($"result = {enumName}.{memberName};");
			sb.AppendLine("return true;");
			sb.Outdent();
		}
		sb.AppendLine("default:");
		sb.Indent();
		sb.AppendLine("result = default;");
		sb.AppendLine("return false;");
		sb.Outdent();
		sb.CloseBrace();
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendTryParseFastFlags(SourceBuilder sb, string enumName)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine("/// Tries to convert the specified <paramref name=\"value\"/>, containing one or more");
		sb.AppendLine("/// member names delimited by any of the <paramref name=\"separators\"/>, to its combined");
		sb.AppendLine($"/// <see cref=\"{enumName}\"/> equivalent.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"value\">The delimited names of the enumeration values to parse.</param>");
		sb.AppendLine("/// <param name=\"result\">The combined enumeration value, or the default value if parsing failed.</param>");
		sb.AppendLine("/// <param name=\"separators\">The delimiters between the member names, for example <c>\"|\"</c>, <c>\",\"</c>, <c>\";\"</c> or <c>\" \"</c>.</param>");
		sb.AppendLine("/// <returns>True if every name in <paramref name=\"value\"/> was parsed successfully; otherwise, false.</returns>");
		sb.AppendLine($"public static bool TryParseFast(string? value, out {enumName} result, params string[] separators)");
		sb.OpenBrace();
		sb.AppendLine("if (value is null || separators is null || separators.Length == 0)");
		sb.Indent();
		sb.AppendLine("return TryParseFast(value, out result);");
		sb.Outdent();
		sb.AppendLine();
		sb.AppendLine($"{enumName} combined = default;");
		sb.AppendLine("bool parsed = false;");
		sb.AppendLine("foreach (string token in value.Split(separators, StringSplitOptions.RemoveEmptyEntries))");
		sb.OpenBrace();
		sb.AppendLine("string name = token.Trim();");
		sb.AppendLine("if (name.Length == 0)");
		sb.Indent();
		sb.AppendLine("continue;");
		sb.Outdent();
		sb.AppendLine();
		sb.AppendLine($"if (!TryParseFast(name, out {enumName} flag))");
		sb.OpenBrace();
		sb.AppendLine("result = default;");
		sb.AppendLine("return false;");
		sb.CloseBrace();
		sb.AppendLine();
		sb.AppendLine("combined |= flag;");
		sb.AppendLine("parsed = true;");
		sb.CloseBrace();
		sb.AppendLine();
		sb.AppendLine("result = parsed ? combined : default;");
		sb.AppendLine("return parsed;");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendGetNamesFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendSummary($"Returns the names of the <see cref=\"{enumName}\"/> enumeration as an collection of strings.");
		sb.AppendLine("/// <returns>An array of strings containing the names of the enumeration values.</returns>");
		sb.AppendLine($"public static IEnumerable<string> GetNamesFast()");
		sb.OpenBrace();
		sb.AppendLine("return new[]");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members)
		{
			sb.AppendLine($"nameof({enumName}.{memberName}),");
		}
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendGetValuesFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendSummary($"Returns the values of the <see cref=\"{enumName}\"/> enumeration.");
		sb.AppendLine("/// <returns>An collection of the enumeration values.</returns>");
		sb.AppendLine($"public static IEnumerable<{enumName}> GetValuesFast()");
		sb.OpenBrace();
		sb.AppendLine("return new[]");
		sb.OpenBrace();
		foreach ((string memberName, _, _) in members)
		{
			sb.AppendLine($"{enumName}.{memberName},");
		}
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static void AppendGetDescriptionFast(SourceBuilder sb, string enumName, EquatableArray<(string Name, string? Description, bool IsAlias)> members)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine($"/// Returns the description of the <see cref=\"{enumName}\"/> enumeration if the");
		sb.AppendLine($"/// <see cref=\"{TypeNames.DescriptionAttribute}\"/> is applied to the");
		sb.AppendLine("/// enumeration value; otherwise, returns the name of the enumeration value.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine("/// <param name=\"value\">The enumeration value to get the description for.</param>");
		sb.AppendLine("/// <returns>The description of the enumeration value, or its name if no description is set.</returns>");
		sb.AppendLine($"public static string GetDescriptionFast(this {enumName} value)");
		sb.OpenBrace();
		sb.AppendLine("return value switch");
		sb.OpenBrace();
		foreach ((string memberName, string? description, _) in members.Where(member => !member.IsAlias))
		{
			if (description is not null)
				sb.AppendLine($"{enumName}.{memberName} => \"{description}\",");
			else
				sb.AppendLine($"{enumName}.{memberName} => nameof({enumName}.{memberName}),");
		}
		sb.AppendLine("_ => value.ToString()");
		sb.Outdent();
		sb.AppendLine("};");
		sb.CloseBrace();
		sb.AppendLine();
	}

	private static string? GetDescriptionFromAttributes(EnumMemberDeclarationSyntax member, SemanticModel semanticModel, INamedTypeSymbol? descriptionAttributeSymbol)
	{
		if (descriptionAttributeSymbol is null)
			return null;

		foreach (AttributeListSyntax attributeList in member.AttributeLists)
		{
			foreach (AttributeSyntax attribute in attributeList.Attributes)
			{
				SymbolInfo symbolInfo = semanticModel.GetSymbolInfo(attribute);
				if (symbolInfo.Symbol is not IMethodSymbol attributeConstructor)
					continue;

				if (!SymbolEqualityComparer.Default.Equals(attributeConstructor.ContainingType, descriptionAttributeSymbol))
					continue;

				if (attribute.ArgumentList?.Arguments.Count > 0)
				{
					AttributeArgumentSyntax argument = attribute.ArgumentList.Arguments[0];
					Optional<object?> descriptionValue = semanticModel.GetConstantValue(argument.Expression);

					return descriptionValue.HasValue && descriptionValue.Value is string description
						? description
						: argument.ToString().Trim('"');
				}
			}
		}

		return null;
	}
}
