using System.Collections.Immutable;

using BB84.SourceGenerators.Analyzers;
using BB84.SourceGenerators.Attributes;
using BB84.SourceGenerators.Extensions;
using BB84.SourceGenerators.Helpers;
using BB84.SourceGenerators.Requests;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace BB84.SourceGenerators;

/// <summary>
/// Responsible for generating command properties for methods marked with the
/// <see cref="ActionCommandAttribute"/> attribute, and for emitting the command
/// runtime types into the consuming compilation.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ActionCommandGenerator : IIncrementalGenerator
{
	private const string CommandSuffix = "Command";
	private const string AsyncSuffix = "Async";
	private const string CommandsNamespace = $"{NamespaceNames.BB84SourceGeneratorsCommands}";
	private const string IActionCommandName = "IActionCommand";
	private const string IAsyncActionCommandName = "IAsyncActionCommand";
	private const string ActionCommandName = "ActionCommand";
	private const string AsyncActionCommandName = "AsyncActionCommand";

	private static readonly (string MetadataName, string TypeName, string ShortName) AttributeNames =
		GeneratorHelpers.GetAttributeNames<ActionCommandAttribute>();

	private static readonly string[] TemplateNames =
		[IActionCommandName, IAsyncActionCommandName, ActionCommandName, AsyncActionCommandName];

	private static readonly string[] TemplateSources =
		[.. TemplateNames.Select(static name => AttributeSourceRewriter.ReadEmbeddedResource($"Commands.{name}.cs"))];

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(static ctx =>
		{
			for (int i = 0; i < TemplateNames.Length; i++)
				ctx.AddSource($"{NamespaceNames.BB84SourceGeneratorsCommands}.{TemplateNames[i]}.g.cs", BuildTemplateSource(TemplateSources[i]));
		});

		IncrementalValuesProvider<ActionCommandResult> provider =
			context.SyntaxProvider
				.ForAttributeWithMetadataName(
					fullyQualifiedMetadataName: AttributeNames.MetadataName,
					predicate: static (node, _) => node is MethodDeclarationSyntax,
					transform: static (ctx, _) => TransformMethod(ctx))
				.Where(static result => result is not null)
				.Select(static (result, _) => result!);

		context.RegisterSourceOutput(provider, Execute);
	}

	/// <summary>
	/// Gets the name of the command generated for the given method, or <see langword="null"/>
	/// if the method is not marked with the <see cref="ActionCommandAttribute"/> attribute.
	/// </summary>
	/// <param name="method">The method symbol.</param>
	/// <returns>The generated command name, or <see langword="null"/>.</returns>
	internal static string? GetCommandName(IMethodSymbol method)
	{
		AttributeData? attribute = method.GetAttributes().FirstOrDefault(IsActionCommandAttribute);
		return attribute is null ? null : GetCommandName(method, attribute);
	}

	private static bool IsActionCommandAttribute(AttributeData attribute)
		=> attribute.AttributeClass?.Name == AttributeNames.TypeName;

	private static string GetCommandName(IMethodSymbol method, AttributeData attribute)
	{
		string? name = GeneratorHelpers.GetNamedArgument<string?>(attribute, nameof(ActionCommandAttribute.Name), null);
		if (!string.IsNullOrWhiteSpace(name))
			return name!;

		string baseName = method.Name.Length > AsyncSuffix.Length && method.Name.EndsWith(AsyncSuffix, StringComparison.Ordinal)
			? method.Name[..^AsyncSuffix.Length]
			: method.Name;

		return $"{baseName}{CommandSuffix}";
	}

	private static string BuildTemplateSource(string template)
	{
		SourceBuilder sb = new();
		sb.AppendAutoGeneratedWarning(GeneratorNames.ActionCommandGeneratorFullName);
		sb.AppendNullableEnable();
		sb.AppendLine(template);
		return sb.ToString();
	}

	private static ActionCommandResult? TransformMethod(GeneratorAttributeSyntaxContext context)
	{
		if (context.TargetNode is not MethodDeclarationSyntax methodSyntax)
			return null;

		if (context.TargetSymbol is not IMethodSymbol method || context.Attributes.IsEmpty)
			return null;

		AttributeData attribute = context.Attributes[0];
		Location location = methodSyntax.Identifier.GetLocation();
		ImmutableArray<Diagnostic>.Builder diagnostics = ImmutableArray.CreateBuilder<Diagnostic>();

		if (methodSyntax.Parent is not TypeDeclarationSyntax typeSyntax
			|| !IsClassOrRecordClass(typeSyntax)
			|| !typeSyntax.Modifiers.Any(SyntaxKind.PartialKeyword))
		{
			diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandContainingTypeNotPartialDiagnostic, location, method.Name, method.ContainingType.Name));
			return new ActionCommandResult(null, diagnostics.ToImmutable());
		}

		if (!TryGetSignature(method, out bool isAsync, out ITypeSymbol? parameterType, out bool hasCancellationToken))
		{
			diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandUnsupportedSignatureDiagnostic, location, method.Name));
			return new ActionCommandResult(null, diagnostics.ToImmutable());
		}

		INamedTypeSymbol containingType = method.ContainingType;
		string commandName = GetCommandName(method, attribute);
		string fieldName = GeneratorHelpers.PropertyNameToFieldName(commandName);

		string? canExecuteName = GeneratorHelpers.GetNamedArgument<string?>(attribute, nameof(ActionCommandAttribute.CanExecute), null);
		string? exceptionHandlerName = GeneratorHelpers.GetNamedArgument<string?>(attribute, nameof(ActionCommandAttribute.ExceptionHandler), null);
		bool allowConcurrentExecutions = GeneratorHelpers.GetNamedArgument(attribute, nameof(ActionCommandAttribute.AllowConcurrentExecutions), false);
		bool includeCancelCommand = GeneratorHelpers.GetNamedArgument(attribute, nameof(ActionCommandAttribute.IncludeCancelCommand), false);

		if (!isAsync)
		{
			ReportAsyncOnlyOption(diagnostics, location, method.Name, nameof(ActionCommandAttribute.ExceptionHandler), exceptionHandlerName is not null);
			ReportAsyncOnlyOption(diagnostics, location, method.Name, nameof(ActionCommandAttribute.AllowConcurrentExecutions), allowConcurrentExecutions);
			ReportAsyncOnlyOption(diagnostics, location, method.Name, nameof(ActionCommandAttribute.IncludeCancelCommand), includeCancelCommand);
			exceptionHandlerName = null;
			allowConcurrentExecutions = false;
			includeCancelCommand = false;
		}

		string? cancelCommandName = includeCancelCommand
			? $"{(commandName.EndsWith(CommandSuffix, StringComparison.Ordinal) ? commandName[..^CommandSuffix.Length] : commandName)}Cancel{CommandSuffix}"
			: null;

		bool hasError = false;

		if (HasNameConflict(containingType, method, commandName, fieldName, cancelCommandName))
		{
			diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandNameConflictDiagnostic, location, method.Name, commandName));
			hasError = true;
		}

		string? canExecuteExpression = null;
		if (canExecuteName is not null)
		{
			canExecuteExpression = GetCanExecuteExpression(containingType, canExecuteName, method.IsStatic, parameterType);
			if (canExecuteExpression is null)
			{
				diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandInvalidCanExecuteDiagnostic, location, method.Name, canExecuteName));
				hasError = true;
			}
		}

		string? exceptionHandlerExpression = null;
		if (exceptionHandlerName is not null)
		{
			exceptionHandlerExpression = GetExceptionHandlerExpression(containingType, exceptionHandlerName, method.IsStatic);
			if (exceptionHandlerExpression is null)
			{
				diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandInvalidExceptionHandlerDiagnostic, location, method.Name, exceptionHandlerName));
				hasError = true;
			}
		}

		if (hasError)
			return new ActionCommandResult(null, diagnostics.ToImmutable());

		ActionCommandRequest request = new(
			typeSyntax.GetNamespace(),
			GeneratorHelpers.GetAccessibility(typeSyntax),
			containingType.Name,
			typeSyntax is RecordDeclarationSyntax,
			GeneratorHelpers.GetOuterClasses(typeSyntax),
			method.Name,
			method.IsStatic,
			isAsync,
			parameterType?.ToDisplayString(PropertyTypeFormat),
			hasCancellationToken,
			commandName,
			fieldName,
			canExecuteExpression,
			exceptionHandlerExpression,
			allowConcurrentExecutions,
			cancelCommandName);

		return new ActionCommandResult(request, diagnostics.ToImmutable());
	}

	private static readonly SymbolDisplayFormat PropertyTypeFormat =
		SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

	private static bool IsClassOrRecordClass(TypeDeclarationSyntax typeSyntax)
		=> typeSyntax is ClassDeclarationSyntax
			|| (typeSyntax is RecordDeclarationSyntax record && !record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword));

	/// <summary>
	/// Maps the method signature to a command kind.
	/// </summary>
	/// <param name="method">The command method.</param>
	/// <param name="isAsync">Whether the method returns a <c>Task</c>.</param>
	/// <param name="parameterType">The command parameter type, or <see langword="null"/> if none.</param>
	/// <param name="hasCancellationToken">Whether the method accepts a <c>CancellationToken</c>.</param>
	/// <returns><see langword="true"/> if the signature is supported; otherwise, <see langword="false"/>.</returns>
	private static bool TryGetSignature(IMethodSymbol method, out bool isAsync, out ITypeSymbol? parameterType, out bool hasCancellationToken)
	{
		isAsync = false;
		parameterType = null;
		hasCancellationToken = false;

		if (method.IsGenericMethod || method.Parameters.Any(static p => p.RefKind != RefKind.None))
			return false;

		if (method.ReturnsVoid)
		{
			if (method.Parameters.Length > 1)
				return false;

			parameterType = method.Parameters.Length == 1 ? method.Parameters[0].Type : null;
			return true;
		}

		if (method.ReturnType.ToDisplayString() != TypeNames.Task)
			return false;

		isAsync = true;
		ImmutableArray<IParameterSymbol> parameters = method.Parameters;

		switch (parameters.Length)
		{
			case 0:
				return true;
			case 1 when IsCancellationToken(parameters[0].Type):
				hasCancellationToken = true;
				return true;
			case 1:
				parameterType = parameters[0].Type;
				return true;
			case 2 when IsCancellationToken(parameters[1].Type) && !IsCancellationToken(parameters[0].Type):
				parameterType = parameters[0].Type;
				hasCancellationToken = true;
				return true;
			default:
				return false;
		}
	}

	private static bool IsCancellationToken(ITypeSymbol type)
		=> type.ToDisplayString() == TypeNames.CancellationToken;

	private static bool HasNameConflict(INamedTypeSymbol containingType, IMethodSymbol method, string commandName, string fieldName, string? cancelCommandName)
	{
		if (!containingType.GetMembers(commandName).IsEmpty || !containingType.GetMembers(fieldName).IsEmpty)
			return true;

		if (cancelCommandName is not null && !containingType.GetMembers(cancelCommandName).IsEmpty)
			return true;

		// Two [ActionCommand] methods (e.g. overloads) that derive the same command name collide with each other.
		return containingType.GetMembers()
			.OfType<IMethodSymbol>()
			.Where(other => !SymbolEqualityComparer.Default.Equals(other, method))
			.Any(other => GetCommandName(other) == commandName);
	}

	/// <summary>
	/// Builds the guard delegate expression for the given <c>CanExecute</c> member name.
	/// </summary>
	/// <param name="containingType">The type containing the command method.</param>
	/// <param name="memberName">The name of the guard member.</param>
	/// <param name="isStatic">Whether the command is static, requiring a static guard.</param>
	/// <param name="parameterType">The command parameter type, or <see langword="null"/> if none.</param>
	/// <returns>The guard expression, or <see langword="null"/> if no compatible member exists.</returns>
	private static string? GetCanExecuteExpression(INamedTypeSymbol containingType, string memberName, bool isStatic, ITypeSymbol? parameterType)
	{
		string lambdaParameter = parameterType is null ? "()" : "parameter";

		foreach (ISymbol member in GetMembersIncludingBase(containingType, memberName))
		{
			if (isStatic && !member.IsStatic)
				continue;

			switch (member)
			{
				case IPropertySymbol property when property.Type.SpecialType == SpecialType.System_Boolean && !property.IsIndexer && property.GetMethod is not null:
				case IFieldSymbol field when field.Type.SpecialType == SpecialType.System_Boolean:
					return $"{lambdaParameter} => {memberName}";

				case IMethodSymbol guard when guard.ReturnType.SpecialType == SpecialType.System_Boolean && !guard.IsGenericMethod:
					if (guard.Parameters.Length == 0)
						return $"{lambdaParameter} => {memberName}()";
					if (parameterType is not null && guard.Parameters.Length == 1 && guard.Parameters[0].RefKind == RefKind.None
						&& SymbolEqualityComparer.Default.Equals(guard.Parameters[0].Type, parameterType))
						return $"parameter => {memberName}(parameter)";
					break;
			}
		}

		// The guard may be a property generated by the NotificationsGenerator from a bool field,
		// which is not visible to this generator; resolve it through the backing field instead.
		if (!isStatic && IsNotificationsType(containingType) && containingType.GetMembers()
			.OfType<IFieldSymbol>()
			.Any(field => !field.IsStatic && field.Type.SpecialType == SpecialType.System_Boolean && GeneratorHelpers.FieldNameToPropertyName(field.Name) == memberName))
			return $"{lambdaParameter} => {memberName}";

		return null;
	}

	private static bool IsNotificationsType(INamedTypeSymbol type)
		=> type.GetAttributes().Any(static attribute => attribute.AttributeClass?.Name == nameof(GenerateNotificationsAttribute));

	/// <summary>
	/// Builds the exception handler delegate expression for the given member name.
	/// </summary>
	/// <param name="containingType">The type containing the command method.</param>
	/// <param name="memberName">The name of the exception handler method.</param>
	/// <param name="isStatic">Whether the command is static, requiring a static handler.</param>
	/// <returns>The handler expression, or <see langword="null"/> if no compatible method exists.</returns>
	private static string? GetExceptionHandlerExpression(INamedTypeSymbol containingType, string memberName, bool isStatic)
	{
		bool found = GetMembersIncludingBase(containingType, memberName)
			.OfType<IMethodSymbol>()
			.Any(handler => (!isStatic || handler.IsStatic)
				&& handler.ReturnsVoid
				&& !handler.IsGenericMethod
				&& handler.Parameters.Length == 1
				&& handler.Parameters[0].RefKind == RefKind.None
				&& handler.Parameters[0].Type.ToDisplayString() == TypeNames.Exception);

		return found ? $"exception => {memberName}(exception)" : null;
	}

	private static IEnumerable<ISymbol> GetMembersIncludingBase(INamedTypeSymbol type, string memberName)
	{
		for (INamedTypeSymbol? current = type; current is not null; current = current.BaseType)
		{
			foreach (ISymbol member in current.GetMembers(memberName))
			{
				if (SymbolEqualityComparer.Default.Equals(current, type) || member.DeclaredAccessibility != Accessibility.Private)
					yield return member;
			}
		}
	}

	private static void ReportAsyncOnlyOption(ImmutableArray<Diagnostic>.Builder diagnostics, Location location, string methodName, string optionName, bool isSet)
	{
		if (isSet)
			diagnostics.Add(Diagnostic.Create(DiagnosticDescriptors.ActionCommandAsyncOptionOnSyncCommandDiagnostic, location, methodName, optionName));
	}

	private static void Execute(SourceProductionContext context, ActionCommandResult result)
	{
		foreach (Diagnostic diagnostic in result.Diagnostics)
			context.ReportDiagnostic(diagnostic);

		if (result.Request is not ActionCommandRequest request)
			return;

		SourceBuilder sb = new();

		sb.BeginTypeFile(GeneratorNames.ActionCommandGeneratorFullName, request.NamespaceName, request.OuterClasses, []);
		sb.OpenClassOrRecord(request.IsRecord, request.TypeAccessibility, request.TypeName);

		AppendCommandProperty(sb, request);

		if (request.CancelCommandName is not null)
		{
			string staticModifier = request.IsStatic ? "static " : string.Empty;
			sb.AppendLine();
			sb.AppendSummary($"Gets the command that cancels the running execution of <see cref=\"{request.CommandName}\"/>.");
			sb.AppendLine($"public {staticModifier}{CommandsNamespace}.IActionCommand {request.CancelCommandName}");
			sb.Indent();
			sb.AppendLine($"=> {request.CommandName}.CancelCommand;");
			sb.Outdent();
		}

		sb.CloseClassOrRecord(request.IsRecord);
		sb.EndTypeFile(request.OuterClasses);

		GeneratorHelpers.AddTypeSource(context, request.OuterClasses, request.TypeName, request.CommandName, sb);
	}

	private static void AppendCommandProperty(SourceBuilder sb, ActionCommandRequest request)
	{
		string staticModifier = request.IsStatic ? "static " : string.Empty;
		string interfaceName = request.IsAsync ? IAsyncActionCommandName : IActionCommandName;
		string className = request.IsAsync ? AsyncActionCommandName : ActionCommandName;
		string genericArgument = request.ParameterType is null ? string.Empty : $"<{request.ParameterType}>";
		string propertyType = $"{CommandsNamespace}.{interfaceName}{genericArgument}";

		List<string> arguments = [GetExecuteExpression(request)];

		if (request.CanExecuteExpression is not null)
			arguments.Add($"canExecute: {request.CanExecuteExpression}");
		if (request.ExceptionHandlerExpression is not null)
			arguments.Add($"onException: {request.ExceptionHandlerExpression}");
		if (request.AllowConcurrentExecutions)
			arguments.Add("allowConcurrentExecutions: true");

		sb.AppendLine($"private {staticModifier}{propertyType}? {request.FieldName};");
		sb.AppendLine();
		sb.AppendSummary($"Gets the command that invokes <c>{request.MethodName}</c>.");
		sb.AppendLine($"public {staticModifier}{propertyType} {request.CommandName}");
		sb.Indent();
		sb.AppendLine($"=> {request.FieldName} ??= new {CommandsNamespace}.{className}{genericArgument}({string.Join(", ", arguments)});");
		sb.Outdent();
	}

	private static string GetExecuteExpression(ActionCommandRequest request)
	{
		string methodName = request.MethodName;
		bool hasParameter = request.ParameterType is not null;

		if (!request.IsAsync)
			return hasParameter ? $"parameter => {methodName}(parameter)" : $"() => {methodName}()";

		return (hasParameter, request.HasCancellationToken) switch
		{
			(false, false) => $"cancellationToken => {methodName}()",
			(false, true) => $"cancellationToken => {methodName}(cancellationToken)",
			(true, false) => $"(parameter, cancellationToken) => {methodName}(parameter)",
			(true, true) => $"(parameter, cancellationToken) => {methodName}(parameter, cancellationToken)"
		};
	}

	/// <summary>
	/// Carries either a valid <see cref="ActionCommandRequest"/> and/or the diagnostics to report through
	/// the incremental pipeline. Diagnostics cannot be raised from the transform stage, so they are
	/// deferred to <see cref="Execute"/> which has access to the <see cref="SourceProductionContext"/>.
	/// </summary>
	/// <param name="Request">The generation request, or <see langword="null"/> if nothing should be generated.</param>
	/// <param name="Diagnostics">The diagnostics to report.</param>
	private sealed record ActionCommandResult(ActionCommandRequest? Request, ImmutableArray<Diagnostic> Diagnostics);
}
