using System.Collections.Immutable;

using BB84.SourceGenerators.Attributes;
using BB84.SourceGenerators.Helpers;
using BB84.SourceGenerators.Models;
using BB84.SourceGenerators.Requests;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace BB84.SourceGenerators;

/// <summary>
/// Represents a source generator that generates abstractions for static classes.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class AbstractionGenerator : IIncrementalGenerator
{
	private static readonly (string MetadataName, string TypeName, string ShortName) AttributeNames =
		GeneratorHelpers.GetAttributeNames<GenerateAbstractionAttribute>();

	/// <inheritdoc />
	public void Initialize(IncrementalGeneratorInitializationContext context)
		=> GeneratorHelpers.RegisterRequestGenerator<AbstractionRequest>(context, AttributeNames.MetadataName, GeneratorHelpers.IsClassNode, Transform, TrackingNames.Abstraction, Execute);

	private static void Execute(SourceProductionContext context, AbstractionRequest request)
	{
		context.AddSource(GeneratorHelpers.BuildHintName(request.AbstractionName), GenerateAbstractionSource(request));
		context.AddSource(GeneratorHelpers.BuildHintName(request.ImplementationName), GenerateImplementationSource(request));
	}

	/// <summary>
	/// Generates the source code for the abstraction interface based on the given request.
	/// </summary>
	/// <param name="request">
	/// The abstraction request containing information about the target type and generated abstraction.
	/// </param>
	/// <returns>
	/// The generated source code for the abstraction interface.
	/// </returns>
	private static string GenerateAbstractionSource(AbstractionRequest request)
	{
		SourceBuilder sb = new();

		sb.AppendAutoGeneratedWarning(GeneratorNames.AbstractionGeneratorFullName);
		sb.AppendNullableEnable();
		sb.OpenNamespace(request.AbstractionNamespace);
		sb.AppendLine($"{request.AbstractionAccessibility} partial interface {request.AbstractionName}");
		sb.OpenBrace();
		foreach ((string comment, string signature, _) in request.Properties)
		{
			sb.AppendLine(comment);
			sb.AppendLine(signature);
		}
		foreach ((string comment, string signature, _) in request.Methods)
		{
			sb.AppendLine(comment);
			sb.AppendLine($"{signature};");
		}
		sb.CloseBrace();
		sb.CloseNamespace();

		return sb.ToString();
	}

	private static string GenerateImplementationSource(AbstractionRequest request)
	{
		SourceBuilder sb = new();

		sb.AppendAutoGeneratedWarning(GeneratorNames.AbstractionGeneratorFullName);
		sb.AppendNullableEnable();
		if (request.AbstractionNamespace != request.ImplementationNamespace)
		{
			sb.AppendUsing(request.AbstractionNamespace);
			sb.AppendLine();
		}
		sb.OpenNamespace(request.ImplementationNamespace);
		sb.AppendLine($"{request.ImplementationAccessibility} partial class {request.ImplementationName} : {request.AbstractionName}");
		sb.OpenBrace();
		foreach ((string comment, _, string signature) in request.Properties)
		{
			sb.AppendLine(comment);
			sb.AppendLine(signature);
		}
		foreach ((_, string signature, string methodUsing) in request.Methods)
		{
			sb.AppendLine($"public {signature}");
			sb.Indent();
			sb.AppendLine($"=> {methodUsing};");
			sb.Outdent();
		}
		sb.CloseBrace();
		sb.CloseNamespace();
		return sb.ToString();
	}

	/// <summary>
	/// Gets the public static property symbols from the target type, excluding any properties in the exclusion list.
	/// </summary>
	/// <param name="targetType">The target static class.</param>
	/// <param name="excludeProperties">The names of the properties to exclude.</param>
	/// <returns>An enumerable of public static property symbols.</returns>
	private static IEnumerable<IPropertySymbol> GetPropertySymbols(INamedTypeSymbol targetType, string[] excludeProperties)
		=> targetType
			.GetMembers()
			.OfType<IPropertySymbol>()
			.Where(p => p.DeclaredAccessibility == Accessibility.Public && p.IsStatic && !excludeProperties.Contains(p.Name));

	/// <summary>
	/// Gets the set of all property accessor method names (e.g. get_PropertyName, set_PropertyName)
	/// from all public static properties of the target type, so they can be filtered from method generation.
	/// This includes accessors from excluded properties to prevent them from appearing as methods.
	/// </summary>
	/// <param name="targetType">The target static class.</param>
	/// <returns>A set of accessor method names.</returns>
	private static HashSet<string> GetAllPropertyAccessorNames(INamedTypeSymbol targetType)
	{
		HashSet<string> names = [];
		foreach (IPropertySymbol property in targetType.GetMembers().OfType<IPropertySymbol>()
			.Where(p => p.DeclaredAccessibility == Accessibility.Public && p.IsStatic))
		{
			if (property.GetMethod != null)
				names.Add(property.GetMethod.Name);
			if (property.SetMethod != null)
				names.Add(property.SetMethod.Name);
		}
		return names;
	}

	/// <summary>
	/// Gets the public static method symbols from the target type, excluding any methods in the exclusion list
	/// and any property accessor methods.
	/// </summary>
	/// <param name="targetType">The target static class.</param>
	/// <param name="excludeMethods">The names of the methods to exclude.</param>
	/// <param name="propertyAccessorNames">The set of property accessor method names to exclude.</param>
	/// <returns>An enumerable of public static method symbols.</returns>
	private static IEnumerable<IMethodSymbol> GetMethodSymbols(INamedTypeSymbol targetType, string[] excludeMethods, HashSet<string> propertyAccessorNames)
		=> targetType
			.GetMembers()
			.OfType<IMethodSymbol>()
			.Where(m => m.DeclaredAccessibility == Accessibility.Public && m.IsStatic
				&& !excludeMethods.Contains(m.Name)
				&& !propertyAccessorNames.Contains(m.Name));

	/// <summary>
	/// Creates a string representation of the specified method symbol, including its name and parameter list.
	/// </summary>
	/// <param name="targetType">The target static class.</param>
	/// <param name="methodSymbol">The method symbol to represent. Must not be <c>null</c>.</param>
	/// <returns>
	/// A string containing the method's name followed by its parameter names in parentheses, separated by commas.
	/// </returns>
	private static string CreateMethodUsing(INamedTypeSymbol targetType, IMethodSymbol methodSymbol)
	{
		IEnumerable<string> parameters = methodSymbol.Parameters.Select(p => $"{GetCallSiteModifier(p)}{p.Name}");
		return $"{targetType}.{methodSymbol.Name}({string.Join(", ", parameters)})";
	}

	/// <summary>
	/// Creates a string representation of a method signature, including its return type, name, and parameter list.
	/// </summary>
	/// <param name="methodSymbol">
	/// The symbol representing the method to generate the signature for. Must not be <c>null</c>.
	/// </param>
	/// <returns>
	/// A string containing the method's signature in the format: "ReturnType MethodName(Type1 param1, Type2 param2, ...);".
	/// </returns>
	private static string CreateMethodSignature(IMethodSymbol methodSymbol)
	{
		IEnumerable<string> parameters = methodSymbol.Parameters.Select(p => $"{GetParameterModifier(p)}{p.Type} {p.Name}");
		return $"{methodSymbol.ReturnType} {methodSymbol.Name}({string.Join(", ", parameters)})";
	}

	/// <summary>
	/// Creates a property signature for the abstraction interface, including the getter and/or setter.
	/// </summary>
	/// <param name="propertySymbol">The property symbol to generate the signature for.</param>
	/// <returns>A string containing the property signature for the abstraction interface.</returns>
	private static string CreateAbstractionPropertySignature(IPropertySymbol propertySymbol)
	{
		string accessors = GetPropertyAccessors(propertySymbol);
		return $"{propertySymbol.Type} {propertySymbol.Name} {{{accessors}}}";
	}

	/// <summary>
	/// Creates a property implementation that delegates to the target static class.
	/// </summary>
	/// <param name="targetType">The target static class.</param>
	/// <param name="propertySymbol">The property symbol to generate the implementation for.</param>
	/// <returns>A string containing the property implementation.</returns>
	private static string CreateImplementationPropertySignature(INamedTypeSymbol targetType, IPropertySymbol propertySymbol)
	{
		string getter = propertySymbol.GetMethod != null && propertySymbol.GetMethod.DeclaredAccessibility == Accessibility.Public
			? $"get => {targetType}.{propertySymbol.Name};"
			: string.Empty;
		string setter = propertySymbol.SetMethod != null && propertySymbol.SetMethod.DeclaredAccessibility == Accessibility.Public
			? $" set => {targetType}.{propertySymbol.Name} = value;"
			: string.Empty;
		return $"public {propertySymbol.Type} {propertySymbol.Name} {{ {getter}{setter} }}";
	}

	/// <summary>
	/// Gets the accessor string (get; set;) for the given property symbol.
	/// </summary>
	/// <param name="propertySymbol">The property symbol.</param>
	/// <returns>A string containing the applicable accessors.</returns>
	private static string GetPropertyAccessors(IPropertySymbol propertySymbol)
	{
		string getter = propertySymbol.GetMethod != null && propertySymbol.GetMethod.DeclaredAccessibility == Accessibility.Public
			? "get;"
			: string.Empty;
		string setter = propertySymbol.SetMethod != null && propertySymbol.SetMethod.DeclaredAccessibility == Accessibility.Public
			? " set;"
			: string.Empty;
		return $" {getter}{setter} ";
	}

	/// <summary>
	/// Generates an XML documentation comment that inherits documentation from the specified target property.
	/// </summary>
	/// <param name="targetType">The target static class used for documentation inheritance.</param>
	/// <param name="propertySymbol">The symbol representing the property for which the documentation comment is generated.</param>
	/// <returns>
	/// A string containing the XML documentation comment that references the target property using <c>&lt;inheritdoc&gt;</c>.
	/// </returns>
	private static string CreatePropertyComment(INamedTypeSymbol targetType, IPropertySymbol propertySymbol)
		=> $"/// <inheritdoc cref=\"{targetType}.{propertySymbol.Name}\"/>";

	/// <summary>
	/// Generates an XML documentation comment that inherits documentation from the specified target method.
	/// </summary>
	/// <param name="targetType">The target static class used for documentation inheritance.</param>
	/// <param name="methodSymbol">The symbol representing the method for which the documentation comment is generated.</param>
	/// <returns>
	/// A string containing the XML documentation comment that references the target method using <c>&lt;inheritdoc&gt;</c>.
	/// </returns>
	private static string CreateMethodComment(INamedTypeSymbol targetType, IMethodSymbol methodSymbol)
	{
		IEnumerable<string> parameters = methodSymbol.Parameters.Select(p => $"{GetCrefParameterModifier(p)}{GetCrefTypeName(p.Type)}");
		return $"/// <inheritdoc cref=\"{targetType}.{methodSymbol.Name}({string.Join(", ", parameters)})\"/>";
	}

	/// <summary>
	/// Gets the type name suitable for use in XML cref attributes, stripping nullable annotations
	/// and replacing angle brackets with curly braces.
	/// </summary>
	/// <param name="type">The type symbol.</param>
	/// <returns>A cref-safe type name string.</returns>
	private static string GetCrefTypeName(ITypeSymbol type)
		=> type.WithNullableAnnotation(NullableAnnotation.NotAnnotated)
			.ToDisplayString()
			.Replace('<', '{')
			.Replace('>', '}');

	/// <summary>
	/// Gets the C# keyword prefix for a parameter in an XML cref attribute.
	/// Only <c>ref</c> and <c>out</c> are valid in cref attributes.
	/// </summary>
	/// <param name="parameter">The parameter symbol.</param>
	/// <returns>The modifier keyword followed by a space, or an empty string if none applies.</returns>
	private static string GetCrefParameterModifier(IParameterSymbol parameter)
		=> GeneratorHelpers.GetRefKindModifier(parameter, includeIn: false, includeParams: false, includeRefReadOnly: false);

	/// <summary>
	/// Gets the C# keyword prefix for a parameter declaration based on its ref kind and params status.
	/// </summary>
	/// <param name="parameter">The parameter symbol.</param>
	/// <returns>The modifier keyword followed by a space, or an empty string if none applies.</returns>
	private static string GetParameterModifier(IParameterSymbol parameter)
		=> GeneratorHelpers.GetRefKindModifier(parameter, includeIn: true, includeParams: true, includeRefReadOnly: false);

	/// <summary>
	/// Gets the C# keyword prefix for a call-site argument based on its ref kind.
	/// </summary>
	/// <param name="parameter">The parameter symbol.</param>
	/// <returns>The modifier keyword followed by a space, or an empty string if none applies.</returns>
	private static string GetCallSiteModifier(IParameterSymbol parameter)
		=> GeneratorHelpers.GetRefKindModifier(parameter, includeIn: false, includeParams: false, includeRefReadOnly: false);

	/// <summary>
	/// Retrieves the fully qualified namespace of the specified type symbol.
	/// </summary>
	/// <remarks>
	/// This method excludes the global namespace from the result. Use this method to obtain
	/// the complete namespace path for code generation or analysis scenarios.
	/// </remarks>
	/// <param name="symbol">
	/// The <see cref="INamedTypeSymbol"/> representing the type whose namespace is to be obtained.
	/// </param>
	/// <returns>
	/// A string containing the full namespace of the type, with segments separated by periods.
	/// Returns an empty string if the type is declared in the global namespace.
	/// </returns>
	private static string GetFullNamespace(INamedTypeSymbol symbol)
	{
		var ns = symbol.ContainingNamespace;
		if (ns == null || ns.IsGlobalNamespace)
			return string.Empty;

		var parts = new List<string>();
		while (ns != null && !ns.IsGlobalNamespace)
		{
			parts.Insert(0, ns.Name);
			ns = ns.ContainingNamespace;
		}
		return string.Join(".", parts);
	}

	/// <summary>
	/// Creates the <see cref="AbstractionRequest"/> for a class decorated with the <see cref="GenerateAbstractionAttribute"/>.
	/// </summary>
	/// <param name="context">The attribute syntax context.</param>
	/// <param name="cancellationToken">The cancellation token.</param>
	/// <returns>
	/// The result carrying the request if the attribute names a target, abstraction and implementation type;
	/// otherwise, <see langword="null"/>.
	/// </returns>
	private static GeneratorResult<AbstractionRequest>? Transform(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
	{
		foreach (AttributeData attributeData in context.TargetSymbol.GetAttributes())
		{
			if (attributeData.AttributeClass?.ToDisplayString() == AttributeNames.MetadataName)
			{
				// Extract constructor arguments
				TypedConstant targetTypeArg = attributeData.ConstructorArguments[0];
				TypedConstant abstractionTypeArg = attributeData.ConstructorArguments[1];
				TypedConstant implementationTypeArg = attributeData.ConstructorArguments[2];

				string[] excludeMethods = GetStringArrayArgument(attributeData, nameof(GenerateAbstractionAttribute.ExcludeMethods));
				string[] excludeProperties = GetStringArrayArgument(attributeData, nameof(GenerateAbstractionAttribute.ExcludeProperties));

				if (targetTypeArg.Value is INamedTypeSymbol targetType
					&& abstractionTypeArg.Value is INamedTypeSymbol abstractionType
					&& implementationTypeArg.Value is INamedTypeSymbol implementationType)
					return GeneratorResult<AbstractionRequest>.FromRequest(CreateRequest(targetType, abstractionType, implementationType, excludeMethods, excludeProperties));
			}
		}
		return null;
	}

	private static AbstractionRequest CreateRequest(INamedTypeSymbol targetType, INamedTypeSymbol abstractionType, INamedTypeSymbol implementationType, string[] excludeMethods, string[] excludeProperties)
	{
		HashSet<string> propertyAccessorNames = GetAllPropertyAccessorNames(targetType);

		EquatableArray<(string Comment, string AbstractionSignature, string ImplementationSignature)> properties = GetPropertySymbols(targetType, excludeProperties)
			.Select(p => (CreatePropertyComment(targetType, p), CreateAbstractionPropertySignature(p), CreateImplementationPropertySignature(targetType, p)))
			.ToEquatableArray();

		EquatableArray<(string Comment, string Signature, string Using)> methods = GetMethodSymbols(targetType, excludeMethods, propertyAccessorNames)
			.Select(m => (CreateMethodComment(targetType, m), CreateMethodSignature(m), CreateMethodUsing(targetType, m)))
			.ToEquatableArray();

		return new AbstractionRequest(
			GetFullNamespace(abstractionType),
			GeneratorHelpers.GetAccessibilityKeyword(abstractionType.DeclaredAccessibility),
			abstractionType.Name,
			GetFullNamespace(implementationType),
			GeneratorHelpers.GetAccessibilityKeyword(implementationType.DeclaredAccessibility),
			implementationType.Name,
			properties,
			methods);
	}

	private static string[] GetStringArrayArgument(AttributeData attributeData, string name)
		=> GeneratorHelpers.GetNamedArrayArgument(attributeData, name) is ImmutableArray<TypedConstant> values
			? [.. values.Select(v => v.Value as string ?? string.Empty)]
			: [];
}
