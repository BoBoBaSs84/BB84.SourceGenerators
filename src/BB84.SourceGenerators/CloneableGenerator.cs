using System.Collections.Immutable;

using BB84.SourceGenerators.Attributes;
using BB84.SourceGenerators.Extensions;
using BB84.SourceGenerators.Helpers;
using BB84.SourceGenerators.Models;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace BB84.SourceGenerators;

/// <summary>
/// Responsible for generating clone methods for classes and structs marked
/// with the <see cref="GenerateCloneableAttribute"/> attribute. The generated code includes
/// a <c>Clone()</c> method for shallow copying and a <c>DeepClone()</c> method that
/// recursively deep clones reference-type properties also marked with
/// <see cref="GenerateCloneableAttribute"/> and collection properties, implementing <c>ICloneable</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class CloneableGenerator : IIncrementalGenerator
{
	private static readonly (string MetadataName, string TypeName, string ShortName) AttributeNames =
		GeneratorHelpers.GetAttributeNames<GenerateCloneableAttribute>();

	/// <inheritdoc/>
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		// Register for classes
		GeneratorHelpers.RegisterClassGenerator(context, AttributeNames.MetadataName, ExecuteClass);

		// Register for structs
		GeneratorHelpers.RegisterStructGenerator(context, AttributeNames.MetadataName, ExecuteStruct);
	}

	private void ExecuteClass(SourceProductionContext context, (ClassDeclarationSyntax ClassSyntax, SemanticModel SemanticModel)? input)
	{
		if (!GeneratorHelpers.TryCreateContext(input, out GeneratorContext ctx))
			return;

		HashSet<string> excludedProperties = GeneratorHelpers.GetExcludedProperties(ctx.ClassDeclaration, ctx.SemanticModel, nameof(GenerateCloneableAttribute));
		ImmutableArray<PropertyDescriptor> properties = GeneratorHelpers.GetPropertyDescriptors(ctx.ClassSymbol, excludedProperties, requireSetter: true, cloneableAttributeName: AttributeNames.MetadataName);

		SourceBuilder sb = new();

		sb.BeginTypeFile(GeneratorNames.CloneableGeneratorFullName, ctx.NamespaceName, ctx.OuterClasses, GetUsings(properties));

		AppendPartialClass(sb, ctx.ClassName, ctx.Accessibility, properties);

		sb.EndTypeFile(ctx.OuterClasses);

		GeneratorHelpers.AddTypeSource(context, ctx.OuterClasses, ctx.ClassName, "Cloneable", sb);
	}

	private void ExecuteStruct(SourceProductionContext context, (StructDeclarationSyntax StructSyntax, SemanticModel SemanticModel)? input)
	{
		if (!GeneratorHelpers.TryCreateContext(input, out TypeGeneratorContext ctx))
			return;

		HashSet<string> excludedProperties = GeneratorHelpers.GetExcludedProperties(ctx.ClassDeclaration, ctx.SemanticModel, nameof(GenerateCloneableAttribute));
		ImmutableArray<PropertyDescriptor> properties = GeneratorHelpers.GetPropertyDescriptors(ctx.ClassSymbol, excludedProperties, requireSetter: true, cloneableAttributeName: AttributeNames.MetadataName);

		SourceBuilder sb = new();

		// Structs are emitted without their outer (nesting) classes, unlike classes.
		sb.AppendAutoGeneratedWarning(GeneratorNames.CloneableGeneratorFullName);
		sb.AppendNullableEnable();

		foreach (string @namespace in GetUsings(properties))
			sb.AppendUsing(@namespace);

		sb.AppendLine();
		sb.OpenNamespace(ctx.NamespaceName);

		AppendPartialStruct(sb, ctx.ClassName, ctx.Accessibility, properties);

		sb.CloseNamespace();

		context.AddSource(GeneratorHelpers.BuildHintName(ctx.ClassName, "Cloneable"), sb.ToString());
	}

	private static List<string> GetUsings(ImmutableArray<PropertyDescriptor> properties)
	{
		bool needsGeneric = false;
		bool needsImmutable = false;
		bool needsLinq = false;

		foreach (PropertyDescriptor property in properties)
		{
			if (property.CollectionKind is CollectionKind.List or CollectionKind.Dictionary or CollectionKind.ReadOnlyCollection)
				needsGeneric = true;
			if (property.CollectionKind == CollectionKind.ImmutableArray)
				needsImmutable = true;
			if (property.CollectionKind != CollectionKind.None && (property.IsElementCloneable || property.IsDictionaryValueCloneable))
				needsLinq = true;
		}

		List<string> usings = [NamespaceNames.System];

		if (needsGeneric)
			usings.Add(NamespaceNames.SystemCollectionsGeneric);
		if (needsImmutable)
			usings.Add(NamespaceNames.SystemCollectionsImmutable);
		if (needsLinq)
			usings.Add(NamespaceNames.SystemLinq);

		return usings;
	}

	private static void AppendPartialClass(SourceBuilder sb, string className, string accessibility, ImmutableArray<PropertyDescriptor> properties)
	{
		sb.OpenClass(accessibility, className, "ICloneable");

		AppendCloneMethod(sb, className, properties, isStruct: false);
		sb.AppendLine();
		AppendDeepCloneMethod(sb, className, properties, isStruct: false);
		sb.AppendLine();
		AppendICloneableClone(sb);

		sb.CloseClass();
	}

	private static void AppendPartialStruct(SourceBuilder sb, string structName, string accessibility, ImmutableArray<PropertyDescriptor> properties)
	{
		sb.OpenStruct(accessibility, structName, "ICloneable");

		AppendCloneMethod(sb, structName, properties, isStruct: true);
		sb.AppendLine();
		AppendDeepCloneMethod(sb, structName, properties, isStruct: true);
		sb.AppendLine();
		AppendICloneableClone(sb);

		sb.CloseStruct();
	}

	private static void AppendCloneMethod(SourceBuilder sb, string typeName, ImmutableArray<PropertyDescriptor> properties, bool isStruct)
	{
		sb.AppendSummary($"Creates a shallow copy of this <see cref=\"{typeName}\"/> instance.");
		sb.AppendLine($"/// <returns>A new <see cref=\"{typeName}\"/> instance with the same property values.</returns>");
		sb.AppendLine($"public {typeName} Clone()");
		sb.OpenBrace();

		if (isStruct)
		{
			sb.AppendLine($"{typeName} clone = this;");
		}
		else
		{
			sb.AppendLine($"{typeName} clone = new {typeName}();");
			foreach (PropertyDescriptor property in properties)
				sb.AppendLine($"clone.{property.Name} = this.{property.Name};");
		}

		sb.AppendLine("return clone;");
		sb.CloseBrace();
	}

	private static void AppendDeepCloneMethod(SourceBuilder sb, string typeName, ImmutableArray<PropertyDescriptor> properties, bool isStruct)
	{
		sb.AppendLine("/// <summary>");
		sb.AppendLine($"/// Creates a deep copy of this <see cref=\"{typeName}\"/> instance.");
		sb.AppendLine("/// Reference-type properties marked with <c>[GenerateCloneable]</c> are recursively deep cloned.");
		sb.AppendLine("/// Collection properties are deep copied with their elements.");
		sb.AppendLine("/// </summary>");
		sb.AppendLine($"/// <returns>A new <see cref=\"{typeName}\"/> instance with deeply cloned property values.</returns>");
		sb.AppendLine($"public {typeName} DeepClone()");
		sb.OpenBrace();

		if (isStruct)
			sb.AppendLine($"{typeName} clone = this;");
		else
			sb.AppendLine($"{typeName} clone = new {typeName}();");

		foreach (PropertyDescriptor property in properties)
		{
			AppendDeepCloneProperty(sb, property);
		}

		sb.AppendLine("return clone;");
		sb.CloseBrace();
	}

	private static void AppendDeepCloneProperty(SourceBuilder sb, PropertyDescriptor property)
	{
		string src = $"this.{property.Name}";
		DeepCloneRule rule = DeepCloneRules.TryGetValue(property.CollectionKind, out DeepCloneRule? kindRule) ? kindRule : DefaultDeepCloneRule;
		bool nullAware = rule.SupportsNullable && property.IsNullable;

		string expression = rule.IsCloneable(property)
			? $"{src}{(nullAware ? "?" : string.Empty)}{rule.CloneSuffix}"
			: nullAware
				? $"{src} is not null ? {rule.Copy(property, src)} : null"
				: rule.Copy(property, src);

		sb.AppendLine($"clone.{property.Name} = {expression};");
	}

	private static readonly DeepCloneRule DefaultDeepCloneRule =
		new(static p => p.IsCloneable, "?.DeepClone()", static (_, src) => src, SupportsNullable: false);

	private static readonly Dictionary<CollectionKind, DeepCloneRule> DeepCloneRules = new()
	{
		[CollectionKind.List] = new(
			static p => p.IsElementCloneable,
			".Select(x => x.DeepClone()).ToList()",
			static (p, src) => $"new List<{p.ElementTypeName}>({src})",
			SupportsNullable: true),
		[CollectionKind.Dictionary] = new(
			static p => p.IsDictionaryValueCloneable,
			".ToDictionary(kvp => kvp.Key, kvp => kvp.Value.DeepClone())",
			static (p, src) => $"new Dictionary<{p.ElementTypeName}, {p.DictionaryValueTypeName}>({src})",
			SupportsNullable: true),
		[CollectionKind.Array] = new(
			static p => p.IsElementCloneable,
			".Select(x => x.DeepClone()).ToArray()",
			static (p, src) => $"({p.TypeName}){src}.Clone()",
			SupportsNullable: true),
		// ImmutableArray is a value type; shallow copy is fine for non-cloneable elements
		[CollectionKind.ImmutableArray] = new(
			static p => p.IsElementCloneable,
			".Select(x => x.DeepClone()).ToImmutableArray()",
			static (_, src) => src,
			SupportsNullable: false),
		[CollectionKind.ReadOnlyCollection] = new(
			static p => p.IsElementCloneable,
			".Select(x => x.DeepClone()).ToList().AsReadOnly()",
			static (p, src) => $"new List<{p.ElementTypeName}>({src}).AsReadOnly()",
			SupportsNullable: true),
	};

	private static void AppendICloneableClone(SourceBuilder sb)
	{
		sb.AppendLine("/// <inheritdoc/>");
		sb.AppendLine("object ICloneable.Clone()");
		sb.Indent();
		sb.AppendLine("=> DeepClone();");
		sb.Outdent();
	}

	/// <summary>
	/// Describes how a property of a given collection kind is deep cloned.
	/// </summary>
	/// <param name="IsCloneable">Determines whether the property's elements (or the property itself) are deep cloned.</param>
	/// <param name="CloneSuffix">The expression appended to the source to deep clone it.</param>
	/// <param name="Copy">Builds the copy expression from the property and the source expression when not deep cloned.</param>
	/// <param name="SupportsNullable">Indicates whether nullable properties are guarded against <see langword="null"/>.</param>
	private sealed record DeepCloneRule(
		Func<PropertyDescriptor, bool> IsCloneable,
		string CloneSuffix,
		Func<PropertyDescriptor, string, string> Copy,
		bool SupportsNullable);
}
